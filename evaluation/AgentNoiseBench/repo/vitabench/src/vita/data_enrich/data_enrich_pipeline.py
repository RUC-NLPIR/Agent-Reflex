import json
import os
from pathlib import Path
from typing import Dict, List, Any
from tqdm import tqdm  # 导入tqdm库
from data_enrich import SimpleDataEnrichment, load_json_file, save_json_file

class ConditionalDataEnricher:
    """条件数据丰富处理器（带进度条显示）"""
    
    def __init__(self):
        self.enricher = SimpleDataEnrichment()
        self.progress_bar = None  # 进度条对象
    
    def should_enrich(self, item: Dict) -> bool:
        """
        判断是否需要对当前item进行丰富
        条件：environment中的stores只有一个
        """
        try:
            stores = item.get("environment", {}).get("stores", {})
            
            # 判断stores数量是否为1
            if isinstance(stores, dict):
                return len(stores) == 1
            elif isinstance(stores, list):
                return len(stores) == 1
            
            return False
        except Exception as e:
            print(f"\n判断是否丰富时出错: {e}")
            return False
    
    def process_item(self, item: Dict, pbar: tqdm = None) -> Dict:
        """处理单个item（带进度条更新）"""
        try:
            if self.should_enrich(item):
                if pbar:
                    pbar.set_postfix_str("正在丰富数据...")
                enriched_item = self.enricher.enrich_complete_data(item)
                if pbar:
                    pbar.set_postfix_str("数据丰富完成")
                return enriched_item
            else:
                if pbar:
                    pbar.set_postfix_str("跳过处理")
                return item
        except Exception as e:
            if pbar:
                pbar.set_postfix_str(f"处理失败: {str(e)[:30]}...")
            return item
    
    def process_list(self, data_list: List[Dict]) -> List[Dict]:
        """处理整个数据列表（带进度条）"""
        enriched_list = []
        enriched_count = 0
        
        # 初始化进度条
        with tqdm(data_list, desc="处理进度", unit="item", 
                 bar_format="{l_bar}{bar}| {n_fmt}/{total_fmt} [{postfix}]") as pbar:
            for item in pbar:
                # 处理当前item
                enriched_item = self.process_item(item, pbar)
                
                # 更新统计
                if enriched_item != item:
                    enriched_count += 1
                
                enriched_list.append(enriched_item)
                
                # 短暂暂停使进度条更平滑
                pbar.refresh()
        
        # 打印统计信息
        print(f"\n{'='*40}")
        print(f"{'处理统计':^40}")
        print(f"{'='*40}")
        print(f"总处理item数: {len(data_list)}")
        print(f"丰富item数: {enriched_count}")
        print(f"跳过item数: {len(data_list) - enriched_count}")
        print(f"{'='*40}")
        
        return enriched_list

def main(input_path: str, output_path: str):
    """主处理流程（带进度显示）"""
    print(f"{'='*40}")
    print(f"{'条件数据丰富处理':^40}")
    print(f"{'='*40}")
    print(f"输入文件: {input_path}")
    print(f"输出文件: {output_path}")
    print(f"{'='*40}")
    
    # 1. 加载数据
    try:
        print("\n[1/4] 正在加载原始数据...")
        original_data = load_json_file(input_path)
        if not isinstance(original_data, list):
            raise ValueError("输入数据必须是列表格式")
        print(f"✓ 成功加载 {len(original_data)} 个item")
    except Exception as e:
        print(f"✗ 加载数据失败: {e}")
        return
    
    # 2. 初始化处理器
    print("\n[2/4] 初始化处理器...")
    processor = ConditionalDataEnricher()
    print("✓ 处理器初始化完成")
    
    # 3. 处理数据
    print("\n[3/4] 开始条件数据丰富处理...")
    try:
        enriched_data = processor.process_list(original_data)
        print("✓ 数据丰富处理完成")
    except Exception as e:
        print(f"✗ 数据处理失败: {e}")
        return
    
    # 4. 保存结果
    print("\n[4/4] 正在保存结果...")
    try:
        save_json_file(enriched_data, output_path)
        print(f"✓ 结果已保存至: {output_path}")
    except Exception as e:
        print(f"✗ 保存结果失败: {e}")
        return
    
    print(f"\n{'='*40}")
    print(f"{'处理完成':^40}")
    print(f"{'='*40}")

if __name__ == "__main__":
    # 配置输入输出路径
    # Anchored on this checkout instead of the original /NAS mount; this module is run
    # directly from its own directory (note the flat `from data_enrich import ...` above),
    # so the vita package is not importable and the anchor is recomputed here.
    domain_dir = Path(__file__).parents[3] / "data" / "vita" / "domains" / "delivery"
    input_file = str(domain_dir / "tasks.json")
    output_file = str(domain_dir / "tasks_zh_enriched.json")
    
